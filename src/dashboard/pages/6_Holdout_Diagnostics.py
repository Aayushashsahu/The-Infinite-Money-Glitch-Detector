"""Page 6 — Holdout Diagnostics: 2024 Out-of-Sample Validation & Explicit Portfolio Holdout State.

Presents empirical factor diagnostics for the isolated 2024 out-of-sample period,
evaluating predictive distribution coverage while strictly enforcing the explicit UNAVAILABLE
state for live portfolio execution.

Guiding Principle: Mathematics first. Data second. Prediction third. AI last.
"""

from __future__ import annotations

import pandas as pd
import streamlit as st

from dashboard.artifacts.loader import (
    load_factor_holdout_diagnostics,
    load_holdout_diagnostics,
    load_portfolio_holdout_diagnostics,
)
from dashboard.components.banner import (
    render_holdout_unavailable_banner,
    render_research_banner,
)
from dashboard.components.metrics_card import format_percent, render_metric_card
from dashboard.components.plots.holdout import (
    build_correlation_shifts_figure,
    build_holdout_factor_fan_figure,
)
from dashboard.components.tables import render_data_table

st.set_page_config(
    page_title="Holdout Diagnostics — The Infinite Money Glitch Detector",
    page_icon="🔬",
    layout="wide",
)


def render_page() -> None:
    """Render the Holdout Diagnostics page."""
    # --------------------------------------------------------------------------
    # A. Research Classification Banner
    # --------------------------------------------------------------------------
    render_research_banner(
        data_classification="SIMULATED_RESEARCH_PROXY",
        pit_mode="ESTIMATED_LAG",
        extra_notice="Out-of-sample holdout diagnostics evaluate 2024 predictive factor coverage. Realized factor compatibility does NOT establish executable strategy profitability.",
    )

    st.title("🔬 Out-of-Sample Holdout Diagnostics (2024)")
    st.caption("Predictive Factor Coverage | Realized vs. Calibrated Volatility | Mandatory Portfolio Holdout State")

    # Load authoritative artifacts
    holdout = load_holdout_diagnostics()
    factor_holdout = load_factor_holdout_diagnostics()
    portfolio_holdout = load_portfolio_holdout_diagnostics()

    # --------------------------------------------------------------------------
    # B. 2024 Realized Factor Diagnostics Overview
    # --------------------------------------------------------------------------
    st.subheader("1. 2024 Realized Factor Dynamics Overview")
    st.markdown(
        """
        The 2024 trading year (247 trading days) was strictly isolated from calibration (2020–2023)
        to evaluate how well the stochastic model anticipated subsequent empirical market behavior:
        """
    )

    h_col1, h_col2, h_col3, h_col4, h_col5 = st.columns(5)
    with h_col1:
        render_metric_card(
            label="Realized FX Volatility",
            value=format_percent(holdout.realized_fx_volatility_annualized),
            delta="Normal Regime",
            delta_color="normal",
            help_text="2024 annualized realized EUR/USD daily log-return volatility.",
        )
    with h_col2:
        render_metric_card(
            label="Volatility Ratio",
            value=f"{holdout.volatility_ratio:.3f}",
            delta="Calib: 7.99%",
            delta_color="off",
            help_text="Ratio of 2024 realized volatility to 2020-2023 calibration volatility.",
        )
    with h_col3:
        render_metric_card(
            label="Realized FX Return",
            value=format_percent(holdout.realized_cumulative_return),
            delta="22.9th Percentile",
            delta_color="inverse",
            help_text="Cumulative EUR/USD exchange rate change during 2024.",
        )
    with h_col4:
        render_metric_card(
            label="Realized Max Drawdown",
            value=format_percent(holdout.realized_max_drawdown),
            delta="64.9th Percentile",
            delta_color="inverse",
            help_text="Maximum peak-to-trough drop in EUR/USD exchange rate in 2024.",
        )
    with h_col5:
        render_metric_card(
            label="Two-Sample KS Test",
            value=f"p = {holdout.fx_log_return_ks_pvalue:.4f}",
            delta=f"D = {holdout.fx_log_return_ks_stat:.4f}",
            delta_color="normal",
            help_text="Kolmogorov-Smirnov test between calibration and holdout return distributions.",
        )

    st.divider()

    # --------------------------------------------------------------------------
    # C. Predictive Factor Distribution Diagnostics
    # --------------------------------------------------------------------------
    st.subheader("2. Predictive Factor Distribution Coverage & Correlation Shifts")
    st.markdown(
        """
        Evaluating whether observed 2024 factor outcomes fell within the 95% predictive simulation interval
        generated by the 2020–2023 calibration:
        """
    )

    f_col1, f_col2 = st.columns([1, 1])

    with f_col1:
        st.plotly_chart(
            build_holdout_factor_fan_figure(
                sim_p025=factor_holdout.simulated_fx_return_p025,
                sim_median=factor_holdout.simulated_fx_return_median,
                sim_p975=factor_holdout.simulated_fx_return_p975,
                realized_return=factor_holdout.actual_fx_cumulative_return,
                height=380,
            ),
            use_container_width=True,
        )

    with f_col2:
        st.plotly_chart(
            build_correlation_shifts_figure(
                shifts=holdout.correlation_shifts,
                height=380,
            ),
            use_container_width=True,
        )

    # Statistical caveat notice
    st.info(f"**KOLMOGOROV-SMIRNOV CAVEAT:** {factor_holdout.fx_log_return_ks_caveat}")

    st.divider()

    # --------------------------------------------------------------------------
    # D. Portfolio Holdout — MANDATORY UNAVAILABLE STATE
    # --------------------------------------------------------------------------
    st.subheader("3. Portfolio Holdout: Live Strategy Execution State")

    # Render dedicated institutional holdout unavailable banner
    render_holdout_unavailable_banner(
        reason=portfolio_holdout.reason,
        notes=portfolio_holdout.notes,
    )

    st.markdown(
        """
        ##### Strict Governance Requirements for 2024 Portfolio Holdout
        1. **Zero Execution Evidence**: No live execution, order-book execution, or funded broker accounts operated during 2024.
        2. **Prohibition of Fabrication**: In accordance with the core principle (*Mathematics first. Data second. Prediction third. AI last*), **no portfolio equity curve is simulated, fabricated, or imputed**.
        3. **Honest Reporting**: The portfolio holdout is strictly represented as **`UNAVAILABLE`** (`is_available: false`). It is **never replaced with zero** or imputed from raw factor data.
        4. **Separation of Factor vs. Portfolio**: Proving that the underlying exchange rate distribution was statistically consistent with calibration models does **not** prove that an executable carry trade strategy would have been profitable after order-book spreads, borrow availability, and financing reset frictions.
        """
    )

    st.divider()

    # --------------------------------------------------------------------------
    # E. Validation Conclusions & Methodological Limitations
    # --------------------------------------------------------------------------
    st.subheader("4. Methodological Conclusions & Invariance Summary")

    lim_df = pd.DataFrame(
        [
            {
                "Diagnostic Dimension": "Sample Window Limitation",
                "Assessment": "Single-year holdout window (247 trading days in 2024) does not span a complete credit or macroeconomic cycle.",
            },
            {
                "Diagnostic Dimension": "Volatility Regime Classification",
                "Assessment": "2024 realized FX volatility (6.18%) lies within the NORMAL_VOLATILITY regime (between 20th percentile 5.74% and 80th percentile 9.49%).",
            },
            {
                "Diagnostic Dimension": "Predictive Coverage Bounds",
                "Assessment": "Realized 2024 return (-5.98%) fell at the 22.9th percentile of predictive simulation, well within the 95% interval (-14.95% to +14.84%).",
            },
            {
                "Diagnostic Dimension": "Predictive Reliability Scope",
                "Assessment": "Factor-level predictive coverage demonstrates empirical distribution compatibility over 2024 but does NOT establish permanent forward-looking market predictability or strategy viability.",
            },
        ]
    )
    render_data_table(lim_df)


if __name__ == "__main__":
    render_page()
